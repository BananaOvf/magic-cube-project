namespace MagicCube.Core.Enums
{
    /// <summary>
    /// Represents the three rotation axes (X, Y, Z) of a Magic Cube.
    /// X: Rotate the entire cube in the same direction as an R turn.
    /// Y: Rotate the entire cube in the same direction as a U turn.
    /// Z: Rotate the entire cube in the same direction as an F turn.
    /// </summary>
    public enum Axis
    {
        X, Y, Z
    }
}
